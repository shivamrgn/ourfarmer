# 4. BUILD HARMONIZED ELIGIBILITY RULES (100 RULES)
# -------------------------------------------------------------------------
def build_harmonized_eligibility_rules(audit_rows):
    """
    Reads the base 100 eligibility rules and updates them with decisions from the audit.
    """
    in_csv = REPORTS_DIR / "phase_3c_4_eligibility_rules.csv"
    audit_map = {r["rule_identifier"]: r for r in audit_rows}

    with open(in_csv, "r", encoding="utf-8") as f:
        rules = list(csv.DictReader(f))

    updated_rules = []
    for r in rules:
        rid = r["rule_identifier"]
        if rid in audit_map:
            aud = audit_map[rid]
            decision = aud["final_decision"]
            if decision == "RETAIN_HARD_EXCLUSION":
                r["revised_status"] = "HARD_EXCLUSION"
                r["rule_type"] = "HARD_EXCLUSION"
                r["action_on_violation"] = "Exclude Crop Immediately"
                r["override_permitted"] = "False"
                r["scientific_justification"] = aud["decision_rationale"]
                r["exact_reference"] = f"{aud['institution']}: {aud['document_title']} ({aud['publication_year']}), {aud['exact_page_table_section']}"
            else:
                r["revised_status"] = "SOFT_PENALTY"
                r["rule_type"] = "SOFT_PENALTY"
                r["action_on_violation"] = "Apply Agronomic Penalty"
                r["override_permitted"] = "True"
                r["scientific_justification"] = aud["decision_rationale"]
                r["exact_reference"] = f"{aud['institution']}: {aud['document_title']} ({aud['publication_year']}), {aud['exact_page_table_section']}"
        updated_rules.append(r)

    out_csv = REPORTS_DIR / "phase_3c_4_eligibility_rules.csv"
    fieldnames = list(rules[0].keys())

    with open(out_csv, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for r in updated_rules:
            writer.writerow(r)

    status_counts = {}
    for r in updated_rules:
        st = r["revised_status"]
        status_counts[st] = status_counts.get(st, 0) + 1

    print(f"  OK: Written harmonized {out_csv.name} (Total: {len(updated_rules)})")
    print(f"  Harmonized Rules Breakdown: {status_counts}")
    return updated_rules

