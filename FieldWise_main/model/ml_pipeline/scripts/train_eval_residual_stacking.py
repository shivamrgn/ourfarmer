"""
FieldWise ML Pipeline — Phase 3B.2: Level-1 Residual Stacking CV Engine
Script: train_eval_residual_stacking.py

Targeted Implementation Corrections:
  1. Mathematical Objective Consistency (§8.2, §8.3):
     Objective: L_Ridge(beta) = sum_i w_i * (r_i - x_i @ beta)^2 + lambda_math * ||beta||^2
     Sample weight normalization: bar{w} = (1 / N_train) * sum_i w_i = 1.0
     
     Mathematical Derivation:
       Gradient: nabla_beta L_Ridge(beta) = -2 * X^T @ W @ (r - X @ beta) + 2 * lambda_math * beta = 0
       Normal equation: (X^T @ W @ X + lambda_math * I) @ beta = X^T @ W @ r
       
       In scikit-learn Ridge(alpha=alpha_sklearn) with sample_weight=w:
       Loss minimized: sum_i w_i * (r_i - x_i @ beta)^2 + alpha_sklearn * ||beta||^2
       Normal equation: (X^T @ W @ X + alpha_sklearn * I) @ beta = X^T @ W @ r
       
       Comparing terms: (X^T @ W @ X + lambda_math * I) == (X^T @ W @ X + alpha_sklearn * I)
       Exact Conversion Identity: alpha_sklearn = lambda_math
       
       This exact identity holds for both unweighted models (w_i = 1.0) and equal-crop
       normalized models (bar{w} = 1.0), as well as Candidate 2 Fallback Ridge (lambda_fallback = 1.0).
       
  2. Candidate 2 Fallback Execution Guarantee (§10.3):
     - Every row routed to Case 2 (FALLBACK_RIDGE_PREDICTION) strictly receives the prediction
       generated by `Candidate2_Fallback_Ridge` (r_unified[i] = r_fallback[i]).
     - Fallback models are fitted strictly on that split's permitted, valid training residual rows (M_train=1),
       never touching evaluation residual targets.
     - Strict assertions verify that every evaluation row receives exactly one prediction and a valid
       routing classification.
"""

import os
import sys
import json
import time
import hashlib
import numpy as np
import pandas as pd
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.linear_model import Ridge
from scipy import sparse

# Enforce deterministic single-threaded execution
os.environ["OMP_NUM_THREADS"] = "1"
os.environ["OPENBLAS_NUM_THREADS"] = "1"
os.environ["MKL_NUM_THREADS"] = "1"
os.environ["VECLIB_MAXIMUM_THREADS"] = "1"
os.environ["NUMEXPR_NUM_THREADS"] = "1"
os.environ["PYTHONHASHSEED"] = "42"

LAMBDAS = [0.0001, 0.001, 0.01, 0.1, 1.0, 10.0, 100.0]
ALPHAS = [0.0, 0.25, 0.50, 0.75, 1.0]
Q_VALS = [0.0, 0.25, 0.50, 0.75, 1.0]
STRATA = ["Cereals & Millets", "Pulses & Legumes", "Oilseeds", "Commercial & Horticultural"]

CAT_COLS = ['State', 'DistrictID', 'Crop', 'Season', 'Level_base']
NUM_COLS = ['Crop_Year', 'district_normal_annual_rainfall_mm', 'district_normal_monsoon_rainfall_mm',
            'y_hat_base', 'N_tilde_cell', 'log_sigma2_cell', 'base_key_state_count']
BIN_COLS = ['base_key_cross_state_collision']

CV_SPLITS = [
    {"split_id": 1, "train_folds": [1], "eval_fold": 2, "train_desc": "2003–2005", "eval_desc": "2006–2007", "exp_eval_a": 15363, "exp_eval_b": 19547},
    {"split_id": 2, "train_folds": [1, 2], "eval_fold": 3, "train_desc": "2003–2007", "eval_desc": "2008–2009", "exp_eval_a": 14901, "exp_eval_b": 19064},
    {"split_id": 3, "train_folds": [1, 2, 3], "eval_fold": 4, "train_desc": "2003–2009", "eval_desc": "2010–2011", "exp_eval_a": 14447, "exp_eval_b": 18165},
]


def route_candidate2_predictions(eval_df, stratum_models, c2_locked_lambdas, r_fallback_eval,
                                 train_crop_counts, tax_crops, alpha_multiplier=1.0):
    """
    Authoritative Candidate 2 5-Case Inference Routing Engine (§10.3, §10.4).
    Reusable production function called during both Stage 2 CV tuning and final evaluation.
    
    Evaluates each observation in eval_df against the 5-case routing table:
      Case 1: Mapped, supported stratum (N_stratum_train >= 500), crop seen (N_c,train > 0), not screened, valid features
              -> Status: ACTIVE_STRATUM_PREDICTION (receives active stratum Ridge prediction)
      Case 2: Mapped, under-supported stratum (N_stratum_train < 500), crop seen (N_c,train > 0), not screened, valid features
              -> Status: FALLBACK_RIDGE_PREDICTION (receives Candidate2_Fallback_Ridge prediction)
      Case 3: Mapped crop, but:
              - out-of-support screened -> Status: ZERO_RESIDUAL_OUT_OF_SUPPORT
              - OR unseen in residual training -> Status: ZERO_RESIDUAL_UNSEEN_CROP
              -> Assigned residual: 0.0
      Case 4: Unmapped crop (c not in C_tax)
              -> Status: ZERO_RESIDUAL_UNMAPPED_CROP
              -> Assigned residual: 0.0
      Case 5: Invalid / non-finite features
              -> Status: ZERO_RESIDUAL_INVALID_FEATURE
              -> Assigned residual: 0.0

    Returns:
      r_c2_unified: np.ndarray of assigned residual corrections (len == N)
      pred_cand_2: np.ndarray of final predictions = y_hat_base + alpha * r_c2_unified
      routing_cases: list of int case numbers (1..5)
      routing_statuses: list of string audit statuses
      counts: dict of case counts
    """
    # 1. Schema Precondition: Enforce all required Candidate 2 routing feature columns
    REQUIRED_CANDIDATE2_COLUMNS = [
        'Crop', 'State', 'Season', 'Level_base',
        'Crop_Year', 'district_normal_annual_rainfall_mm', 'district_normal_monsoon_rainfall_mm',
        'y_hat_base', 'N_tilde_cell', 'log_sigma2_cell', 'base_key_state_count',
        'base_key_cross_state_collision', 'is_screened'
    ]
    missing_cols = [c for c in REQUIRED_CANDIDATE2_COLUMNS if c not in eval_df.columns]
    if "DistrictID" not in eval_df.columns and "District" not in eval_df.columns:
        missing_cols.append("DistrictID (or District)")
    if missing_cols:
        raise ValueError(f"Candidate 2 Schema Error: Missing required feature column(s): {missing_cols}")

    n_ev = len(eval_df)
    r_c2_unified = np.zeros(n_ev, dtype=float)
    routing_cases = []
    routing_statuses = []

    active_count = 0
    fallback_count = 0
    screened_count = 0
    unseen_count = 0
    unmapped_count = 0
    invalid_count = 0

    # 2. Fallback Precondition: Assert exact 1-to-1 length and 100% finite entries before routing
    if r_fallback_eval is None:
        raise ValueError("Candidate 2 routing precondition failed: r_fallback_eval is None")
    r_fallback_arr = np.asarray(r_fallback_eval, dtype=float)
    assert len(r_fallback_arr) == n_ev, (
        f"Candidate 2 routing precondition failed: fallback prediction array length ({len(r_fallback_arr)}) "
        f"!= evaluation rows ({n_ev})"
    )
    assert np.all(np.isfinite(r_fallback_arr)), (
        "Candidate 2 routing precondition failed: fallback prediction array contains non-finite values (NaN, +inf, or -inf)"
    )

    # Map stratum active predictions by row index
    active_preds_map = {}
    for s, st in stratum_models.items():
        if st.get("status") == "ACTIVE":
            ev_idx = st.get("ev_indices", eval_df[eval_df["stratum"] == s].index)
            if len(ev_idx) == 0:
                continue
            lam = c2_locked_lambdas.get(s, 1.0) if c2_locked_lambdas else 1.0
            if "active_preds" in st:
                preds = st["active_preds"]
            elif "lam_preds" in st and lam in st["lam_preds"]:
                preds = st["lam_preds"][lam]
            else:
                raise ValueError(f"Active stratum '{s}' missing predictions")
            
            for idx_pos, orig_idx in enumerate(ev_idx):
                active_preds_map[orig_idx] = preds[idx_pos]

    # Authoritative 5-Case Evaluation per Row
    for pos, (orig_idx, row) in enumerate(eval_df.iterrows()):
        c = row["Crop"]
        s = row.get("stratum", None)
        is_feature_valid = bool(row.get("is_feature_valid", True))

        # Explicit validation of is_screened (reject missing, null, or non-boolean values)
        raw_screened = row["is_screened"]
        is_screened = False
        if pd.isna(raw_screened) or raw_screened is None:
            is_feature_valid = False
        elif isinstance(raw_screened, (bool, np.bool_)):
            is_screened = bool(raw_screened)
        elif isinstance(raw_screened, (int, np.integer)) and raw_screened in (0, 1):
            is_screened = bool(raw_screened)
        elif isinstance(raw_screened, str) and raw_screened.strip().lower() in ("true", "1"):
            is_screened = True
        elif isinstance(raw_screened, str) and raw_screened.strip().lower() in ("false", "0"):
            is_screened = False
        else:
            is_feature_valid = False

        # Comprehensive Production Feature Validation
        if is_feature_valid:
            # 1. Numerical Feature Validation (Reject NaN, +inf, -inf, non-numeric)
            for col in [
                'Crop_Year', 'district_normal_annual_rainfall_mm', 'district_normal_monsoon_rainfall_mm',
                'y_hat_base', 'N_tilde_cell', 'log_sigma2_cell', 'base_key_state_count',
                'base_key_cross_state_collision'
            ]:
                val = row[col]
                if pd.isna(val):
                    is_feature_valid = False
                    break
                try:
                    fval = float(val)
                    if not np.isfinite(fval) or np.isnan(fval):
                        is_feature_valid = False
                        break
                except (ValueError, TypeError):
                    is_feature_valid = False
                    break

        if is_feature_valid:
            # 2. Categorical / Model Field Validation (Reject missing, None, empty string)
            for col in ['State', 'Crop', 'Season', 'Level_base']:
                val = row[col]
                if pd.isna(val) or val is None or str(val).strip() == "":
                    is_feature_valid = False
                    break
            if is_feature_valid:
                dist_val = row.get("DistrictID", row.get("District", None))
                if pd.isna(dist_val) or dist_val is None or str(dist_val).strip() == "":
                    is_feature_valid = False

        if not is_feature_valid:
            # Case 5: Invalid / non-finite features
            routing_cases.append(5)
            routing_statuses.append("ZERO_RESIDUAL_INVALID_FEATURE")
            r_c2_unified[pos] = 0.0
            invalid_count += 1
        elif c not in tax_crops:
            # Case 4: Unmapped crop
            routing_cases.append(4)
            routing_statuses.append("ZERO_RESIDUAL_UNMAPPED_CROP")
            r_c2_unified[pos] = 0.0
            unmapped_count += 1
        elif is_screened:
            # Case 3: Out of support screened
            routing_cases.append(3)
            routing_statuses.append("ZERO_RESIDUAL_OUT_OF_SUPPORT")
            r_c2_unified[pos] = 0.0
            screened_count += 1
        elif train_crop_counts.get(c, 0) == 0:
            # Case 3: Mapped crop absent from residual training
            routing_cases.append(3)
            routing_statuses.append("ZERO_RESIDUAL_UNSEEN_CROP")
            r_c2_unified[pos] = 0.0
            unseen_count += 1
        elif s in stratum_models and stratum_models[s].get("status") == "FALLBACK":
            # Case 2: Mapped crop in under-supported stratum (N_stratum_train < 500)
            # Strictly receives Candidate2_Fallback_Ridge prediction!
            routing_cases.append(2)
            routing_statuses.append("FALLBACK_RIDGE_PREDICTION")
            r_c2_unified[pos] = r_fallback_arr[pos]
            fallback_count += 1
        else:
            # Case 1: Mapped, supported, seen, valid active stratum
            routing_cases.append(1)
            routing_statuses.append("ACTIVE_STRATUM_PREDICTION")
            r_c2_unified[pos] = active_preds_map[orig_idx]
            active_count += 1

    y_base = eval_df["y_hat_base"].values
    y_base_safe = np.where(np.isfinite(y_base), y_base, 0.0)
    pred_cand_2 = y_base_safe + alpha_multiplier * r_c2_unified

    counts = {
        "active_count": active_count,
        "fallback_count": fallback_count,
        "screened_count": screened_count,
        "unseen_count": unseen_count,
        "unmapped_count": unmapped_count,
        "invalid_count": invalid_count,
        "total_zero_residual": screened_count + unseen_count + unmapped_count + invalid_count,
        "total_eval": n_ev
    }

    # Post-routing Integrity Assertions
    assert len(pred_cand_2) == n_ev, f"Expected {n_ev} predictions, got {len(pred_cand_2)}"
    assert len(r_c2_unified) == n_ev, f"Expected {n_ev} residual corrections, got {len(r_c2_unified)}"
    assert len(routing_cases) == n_ev, f"Expected {n_ev} routing cases, got {len(routing_cases)}"
    assert len(routing_statuses) == n_ev, f"Expected {n_ev} routing statuses, got {len(routing_statuses)}"

    VALID_ROUTING_CASES = {1, 2, 3, 4, 5}
    VALID_ROUTING_STATUSES = {
        "ACTIVE_STRATUM_PREDICTION",
        "FALLBACK_RIDGE_PREDICTION",
        "ZERO_RESIDUAL_OUT_OF_SUPPORT",
        "ZERO_RESIDUAL_UNSEEN_CROP",
        "ZERO_RESIDUAL_UNMAPPED_CROP",
        "ZERO_RESIDUAL_INVALID_FEATURE"
    }
    for i in range(n_ev):
        assert routing_cases[i] in VALID_ROUTING_CASES, f"Row {i} has invalid routing case: {routing_cases[i]}"
        assert routing_statuses[i] in VALID_ROUTING_STATUSES, f"Row {i} has invalid routing status: {routing_statuses[i]}"

    assert np.all(np.isfinite(r_c2_unified)), "Post-routing failure: Non-finite residual correction found!"
    assert np.all(np.isfinite(pred_cand_2)), "Post-routing failure: Non-finite final prediction found!"

    reconciled_count = counts["active_count"] + counts["fallback_count"] + counts["total_zero_residual"]
    assert reconciled_count == n_ev, f"Post-routing reconciliation mismatch: {reconciled_count} != {n_ev}"
    assert counts["total_eval"] == n_ev, f"Total eval count mismatch: {counts['total_eval']} != {n_ev}"

    return r_c2_unified, pred_cand_2, routing_cases, routing_statuses, counts


def run_residual_cv_for_experiment(experiment_id, oof_csv_path, taxonomy_path):
    print(f"\n=======================================================")
    print(f"Running Level-1 Residual CV for: {experiment_id}")
    print(f"=======================================================")
    t0 = time.time()

    with open(taxonomy_path, "r", encoding="utf-8") as f:
        tax = json.load(f)
    crop2stratum = {c: info["stratum"] for c, info in tax["crops"].items()}
    tax_crops = set(tax["crops"].keys())

    df = pd.read_csv(oof_csv_path)
    df["DistrictID"] = df["State"] + "__" + df["District"]
    df["stratum"] = df["Crop"].map(crop2stratum)

    is_exp_a = "experiment_a" in experiment_id
    total_expected_eval = sum(s["exp_eval_a"] if is_exp_a else s["exp_eval_b"] for s in CV_SPLITS)
    print(f"  Loaded {len(df)} OOF records. Expected total CV evaluation rows: {total_expected_eval}")

    splits_data = []

    for s_info in CV_SPLITS:
        s_id = s_info["split_id"]
        exp_eval_count = s_info["exp_eval_a"] if is_exp_a else s_info["exp_eval_b"]

        train_raw = df[df["base_fold"].isin(s_info["train_folds"])].copy()
        eval_raw = df[df["base_fold"] == s_info["eval_fold"]].copy()

        assert len(eval_raw) == exp_eval_count, f"Split {s_id}: expected {exp_eval_count} eval rows, found {len(eval_raw)}"

        # Step 1: Raw Validity Checks
        # Step 2: Training-fitted rainfall normal median calculation
        ann_state_med = train_raw.groupby("State")["district_normal_annual_rainfall_mm"].median()
        ann_glob_med = float(train_raw["district_normal_annual_rainfall_mm"].median())
        mon_state_med = train_raw.groupby("State")["district_normal_monsoon_rainfall_mm"].median()
        mon_glob_med = float(train_raw["district_normal_monsoon_rainfall_mm"].median())

        # Step 3: Impute rainfall and construct log_sigma2_cell
        for d in [train_raw, eval_raw]:
            d["district_normal_annual_rainfall_mm"] = (
                d["district_normal_annual_rainfall_mm"]
                .fillna(d["State"].map(ann_state_med))
                .fillna(ann_glob_med)
            )
            d["district_normal_monsoon_rainfall_mm"] = (
                d["district_normal_monsoon_rainfall_mm"]
                .fillna(d["State"].map(mon_state_med))
                .fillna(mon_glob_med)
            )
            d["log_sigma2_cell"] = np.log(d["sigma2_cell"] + 1e-4)

        # Split-local out-of-support bounds
        bounds = train_raw.groupby("Crop")["y_hat_base"].agg(["min", "max"]).to_dict(orient="index")
        train_crop_counts = train_raw["Crop"].value_counts().to_dict()

        # Step 4: Master Feature Space Preparation (Candidate 1 & Fallback Ridge)
        ohe_master = OneHotEncoder(handle_unknown="ignore", sparse_output=True)
        X_tr_cat = ohe_master.fit_transform(train_raw[CAT_COLS])
        X_ev_cat = ohe_master.transform(eval_raw[CAT_COLS])

        scaler_master = StandardScaler()
        X_tr_num = scaler_master.fit_transform(train_raw[NUM_COLS])
        X_ev_num = scaler_master.transform(eval_raw[NUM_COLS])

        X_tr_master = sparse.hstack([X_tr_cat, sparse.csr_matrix(X_tr_num), sparse.csr_matrix(train_raw[BIN_COLS].values)]).tocsr()
        X_ev_master = sparse.hstack([X_ev_cat, sparse.csr_matrix(X_ev_num), sparse.csr_matrix(eval_raw[BIN_COLS].values)]).tocsr()

        y_tr = train_raw["residual"].values

        # Out-of-support screening mask on eval_raw (§7.3)
        # Rule 1: Level_base >= 6 -> screened (force r_pred = 0)
        # Rule 2: y_hat_base outside [y_min,c, y_max,c] -> screened (force r_pred = 0)
        screened_flags = []
        for row in eval_raw.itertuples():
            if row.Level_base >= 6:
                screened_flags.append("RULE_1_LEVEL_GE_6")
            elif row.Crop not in bounds:
                screened_flags.append("RULE_2_EXTRAPOLATION")
            elif row.y_hat_base < bounds[row.Crop]["min"] or row.y_hat_base > bounds[row.Crop]["max"]:
                screened_flags.append("RULE_2_EXTRAPOLATION")
            else:
                screened_flags.append("IN_SUPPORT")

        eval_raw["screening_status"] = screened_flags
        eval_raw["is_screened"] = eval_raw["screening_status"] != "IN_SUPPORT"

        # Fit Candidate 1 Unweighted Ridge models across lambdas
        # Mathematical identity: alpha_sklearn = lambda_math
        c1_unw_models = {}
        for lam in LAMBDAS:
            alpha_sk = lam  # Directly minimizes sum_i (r_i - x_i @ beta)^2 + lam * ||beta||^2
            clf = Ridge(alpha=alpha_sk, fit_intercept=True, solver="auto", random_state=42)
            clf.fit(X_tr_master, y_tr)
            r_pred = clf.predict(X_ev_master)
            r_screened = np.where(eval_raw["is_screened"], 0.0, r_pred)
            c1_unw_models[lam] = r_screened

        # Fit Candidate 1 Equal-Crop Weighted Ridge models across lambdas
        # w_i = (1 / N_c) / mean(1 / N_c) so bar{w} = 1.0
        raw_w = train_raw["Crop"].map(lambda c: 1.0 / train_crop_counts[c]).values
        norm_w = raw_w / np.mean(raw_w)
        c1_eq_models = {}
        for lam in LAMBDAS:
            alpha_sk = lam  # Directly minimizes sum_i w_i * (r_i - x_i @ beta)^2 + lam * ||beta||^2
            clf = Ridge(alpha=alpha_sk, fit_intercept=True, solver="auto", random_state=42)
            clf.fit(X_tr_master, y_tr, sample_weight=norm_w)
            r_pred = clf.predict(X_ev_master)
            r_screened = np.where(eval_raw["is_screened"], 0.0, r_pred)
            c1_eq_models[lam] = r_screened

        # Fit Candidate 2 Fallback Ridge (fixed lambda_fallback = 1.0)
        # Mathematical identity: alpha_sklearn = lambda_fallback = 1.0
        clf_c2_fb = Ridge(alpha=1.0, fit_intercept=True, solver="auto", random_state=42)
        clf_c2_fb.fit(X_tr_master, y_tr)
        r_pred_fb = clf_c2_fb.predict(X_ev_master)
        r_fb_screened = np.where(eval_raw["is_screened"], 0.0, r_pred_fb)

        # Fit Candidate 2 Stratum models
        c2_stratum_models = {}
        for s in STRATA:
            tr_s = train_raw[train_raw["stratum"] == s]
            ev_s = eval_raw[eval_raw["stratum"] == s]
            n_tr_s = len(tr_s)

            if n_tr_s >= 500: # ACTIVE STRATUM
                ohe_s = OneHotEncoder(handle_unknown="ignore", sparse_output=True)
                X_tr_cat_s = ohe_s.fit_transform(tr_s[CAT_COLS])
                scaler_s = StandardScaler()
                X_tr_num_s = scaler_s.fit_transform(tr_s[NUM_COLS])
                X_tr_s = sparse.hstack([X_tr_cat_s, sparse.csr_matrix(X_tr_num_s), sparse.csr_matrix(tr_s[BIN_COLS].values)]).tocsr()
                y_tr_s = tr_s["residual"].values

                X_ev_cat_s = ohe_s.transform(ev_s[CAT_COLS])
                X_ev_num_s = scaler_s.transform(ev_s[NUM_COLS])
                X_ev_s = sparse.hstack([X_ev_cat_s, sparse.csr_matrix(X_ev_num_s), sparse.csr_matrix(ev_s[BIN_COLS].values)]).tocsr()

                # Active evaluation rows: crop seen in training and not screened
                ev_s_act_mask = (ev_s["Crop"].map(lambda c: train_crop_counts.get(c, 0) > 0)) & (~ev_s["is_screened"])

                lam_preds = {}
                for lam in LAMBDAS:
                    alpha_sk = lam  # Directly minimizes sum_{i in s} (r_i - x_i @ beta)^2 + lam * ||beta||^2
                    clf_s = Ridge(alpha=alpha_sk, fit_intercept=True, solver="auto", random_state=42)
                    clf_s.fit(X_tr_s, y_tr_s)
                    r_pred_s = clf_s.predict(X_ev_s)
                    lam_preds[lam] = r_pred_s

                c2_stratum_models[s] = {
                    "status": "ACTIVE",
                    "n_tr": n_tr_s,
                    "ev_indices": ev_s.index,
                    "ev_act_mask": ev_s_act_mask.values,
                    "lam_preds": lam_preds
                }
            else: # LOW-SUPPORT STRATUM -> FALLBACK
                c2_stratum_models[s] = {
                    "status": "FALLBACK",
                    "n_tr": n_tr_s,
                    "ev_indices": ev_s.index
                }

        splits_data.append({
            "split_id": s_id,
            "train_df": train_raw,
            "eval_df": eval_raw,
            "train_crop_counts": train_crop_counts,
            "bounds": bounds,
            "c1_unw_models": c1_unw_models,
            "c1_eq_models": c1_eq_models,
            "c2_stratum_models": c2_stratum_models,
            "r_c2_fallback": r_fb_screened
        })

    # -------------------------------------------------------------
    # Candidate 0A & 0B Tuning
    # -------------------------------------------------------------
    print("  [Tuning] Candidate 0A & Candidate 0B...")
    scores_0a = {}
    for q in Q_VALS:
        errs = []
        for sd in splits_data:
            tr = sd["train_df"]
            ev = sd["eval_df"]
            r_glob = tr["residual"].mean()
            y_pred = ev["y_hat_base"] + q * r_glob
            errs.extend(np.abs(ev["Yield_Tonnes_Per_Ha"] - y_pred).tolist())
        scores_0a[q] = float(np.mean(errs))

    best_q_0a = min(scores_0a.keys(), key=lambda q: (scores_0a[q], q))
    print(f"    Cand 0A Best: q={best_q_0a}, CV MAE = {scores_0a[best_q_0a]:.6f} t/ha")

    scores_0b = {}
    for q in Q_VALS:
        errs = []
        for sd in splits_data:
            tr = sd["train_df"]
            ev = sd["eval_df"]
            r_glob = tr["residual"].mean()
            r_crop = tr.groupby("Crop")["residual"].mean().to_dict()
            crop_res = ev["Crop"].map(r_crop).fillna(r_glob)
            y_pred = ev["y_hat_base"] + q * crop_res
            errs.extend(np.abs(ev["Yield_Tonnes_Per_Ha"] - y_pred).tolist())
        scores_0b[q] = float(np.mean(errs))

    best_q_0b = min(scores_0b.keys(), key=lambda q: (scores_0b[q], q))
    print(f"    Cand 0B Best: q={best_q_0b}, CV MAE = {scores_0b[best_q_0b]:.6f} t/ha")

    # -------------------------------------------------------------
    # Candidate 1 Unweighted & Equal-Crop Tuning
    # -------------------------------------------------------------
    print("  [Tuning] Candidate 1 (Unweighted)...")
    scores_1_unw = {}
    best_c1_unw = None
    min_mae_1_unw = 999.0

    for lam in LAMBDAS:
        for alpha in ALPHAS:
            errs = []
            for sd in splits_data:
                ev = sd["eval_df"]
                r_pred = sd["c1_unw_models"][lam]
                y_pred = ev["y_hat_base"] + alpha * r_pred
                errs.extend(np.abs(ev["Yield_Tonnes_Per_Ha"] - y_pred).tolist())
            mae = float(np.mean(errs))
            scores_1_unw[(lam, alpha)] = mae
            if mae < min_mae_1_unw - 1e-7:
                min_mae_1_unw = mae
                best_c1_unw = (lam, alpha)
            elif abs(mae - min_mae_1_unw) <= 1e-7:
                # Tie break (§10.5): highest lambda, lowest alpha
                if lam > best_c1_unw[0] or (lam == best_c1_unw[0] and alpha < best_c1_unw[1]):
                    min_mae_1_unw = mae
                    best_c1_unw = (lam, alpha)

    print(f"    Cand 1 Unweighted Best: lam={best_c1_unw[0]}, alpha={best_c1_unw[1]}, CV MAE = {min_mae_1_unw:.6f} t/ha")

    print("  [Tuning] Candidate 1 (Equal-Crop)...")
    scores_1_eq = {}
    best_c1_eq = None
    min_mae_1_eq = 999.0

    for lam in LAMBDAS:
        for alpha in ALPHAS:
            errs = []
            for sd in splits_data:
                ev = sd["eval_df"]
                r_pred = sd["c1_eq_models"][lam]
                y_pred = ev["y_hat_base"] + alpha * r_pred
                errs.extend(np.abs(ev["Yield_Tonnes_Per_Ha"] - y_pred).tolist())
            mae = float(np.mean(errs))
            scores_1_eq[(lam, alpha)] = mae
            if mae < min_mae_1_eq - 1e-7:
                min_mae_1_eq = mae
                best_c1_eq = (lam, alpha)
            elif abs(mae - min_mae_1_eq) <= 1e-7:
                if lam > best_c1_eq[0] or (lam == best_c1_eq[0] and alpha < best_c1_eq[1]):
                    min_mae_1_eq = mae
                    best_c1_eq = (lam, alpha)

    print(f"    Cand 1 Equal-Crop Best: lam={best_c1_eq[0]}, alpha={best_c1_eq[1]}, CV MAE = {min_mae_1_eq:.6f} t/ha")

    # -------------------------------------------------------------
    # Candidate 2: Stage 1 (Stratum Lambda Selection)
    # -------------------------------------------------------------
    print("  [Tuning] Candidate 2 Stage 1 (Stratum Regularization Selection)...")
    c2_locked_lambdas = {}
    stage1_diag = {}

    for s in STRATA:
        best_lam = None
        min_mae_s = 999.0
        lam_scores_s = {}
        total_act_eval = 0

        for lam in LAMBDAS:
            errs = []
            for sd in splits_data:
                st = sd["c2_stratum_models"][s]
                if st["status"] == "ACTIVE":
                    ev = sd["eval_df"]
                    ev_s = ev.loc[st["ev_indices"]]
                    act_m = st["ev_act_mask"]
                    if np.any(act_m):
                        y_true = ev_s.loc[ev_s.index[act_m], "Yield_Tonnes_Per_Ha"].values
                        y_base = ev_s.loc[ev_s.index[act_m], "y_hat_base"].values
                        r_pred = st["lam_preds"][lam][act_m]
                        errs.extend(np.abs(y_true - (y_base + 1.0 * r_pred)).tolist())
            total_act_eval = len(errs)
            mae_s = float(np.mean(errs)) if len(errs) > 0 else 999.0
            lam_scores_s[lam] = mae_s
            if mae_s < min_mae_s - 1e-7:
                min_mae_s = mae_s
                best_lam = lam
            elif abs(mae_s - min_mae_s) <= 1e-7:
                if lam > best_lam:
                    min_mae_s = mae_s
                    best_lam = lam

        if total_act_eval == 0:
            best_lam = 1.0
            diag_note = "LAMBDA_NOT_EMPIRICALLY_SELECTED (DEFAULT_LAMBDA_APPLIED: 1.0)"
        else:
            diag_note = f"EMPIRICALLY_TUNED (Active Eval MAE: {min_mae_s:.6f} t/ha, N={total_act_eval})"

        c2_locked_lambdas[s] = best_lam
        stage1_diag[s] = {
            "optimal_lambda": best_lam,
            "min_mae": min_mae_s,
            "active_eval_count": total_act_eval,
            "status_note": diag_note,
            "lambda_grid_scores": {str(k): v for k, v in lam_scores_s.items()}
        }
        print(f"    Stratum '{s}': lambda* = {best_lam} | {diag_note}")

    # -------------------------------------------------------------
    # Candidate 2: Stage 2 (Shared Multiplier Selection & Full Fallback Routing)
    # -------------------------------------------------------------
    print("  [Tuning] Candidate 2 Stage 2 (Shared Alpha Multiplier Selection)...")
    scores_2 = {}
    best_alpha_2 = None
    min_mae_2 = 999.0

    for alpha in ALPHAS:
        errs = []
        for sd in splits_data:
            ev = sd["eval_df"]
            _, y_pred, _, _, _ = route_candidate2_predictions(
                eval_df=ev,
                stratum_models=sd["c2_stratum_models"],
                c2_locked_lambdas=c2_locked_lambdas,
                r_fallback_eval=sd["r_c2_fallback"],
                train_crop_counts=sd["train_crop_counts"],
                tax_crops=tax_crops,
                alpha_multiplier=alpha
            )
            errs.extend(np.abs(ev["Yield_Tonnes_Per_Ha"].values - y_pred).tolist())

        mae = float(np.mean(errs))
        scores_2[alpha] = mae
        if mae < min_mae_2 - 1e-7:
            min_mae_2 = mae
            best_alpha_2 = alpha
        elif abs(mae - min_mae_2) <= 1e-7:
            if alpha < best_alpha_2: # tie break: lowest alpha
                min_mae_2 = mae
                best_alpha_2 = alpha

    print(f"    Cand 2 Best: alpha*={best_alpha_2}, CV MAE = {min_mae_2:.6f} t/ha")

    # -------------------------------------------------------------
    # Overall Candidate Selection (§10.5)
    # -------------------------------------------------------------
    candidate_summary = {
        "Candidate 0A": {"cv_mae": scores_0a[best_q_0a], "best_param": {"q": best_q_0a}},
        "Candidate 0B": {"cv_mae": scores_0b[best_q_0b], "best_param": {"q": best_q_0b}},
        "Candidate 1 Unweighted": {"cv_mae": min_mae_1_unw, "best_param": {"lambda": best_c1_unw[0], "alpha": best_c1_unw[1]}},
        "Candidate 1 Equal-Crop": {"cv_mae": min_mae_1_eq, "best_param": {"lambda": best_c1_eq[0], "alpha": best_c1_eq[1]}},
        "Candidate 2": {"cv_mae": min_mae_2, "best_param": {"stratum_lambdas": c2_locked_lambdas, "alpha": best_alpha_2}}
    }

    min_cv_mae = min(c["cv_mae"] for c in candidate_summary.values())
    tied_candidates = [name for name, c in candidate_summary.items() if c["cv_mae"] <= min_cv_mae + 1e-7]

    # Pre-registered tie hierarchy (§10.5): Cand 0A > Cand 0B > Cand 1 Unw > Cand 1 Eq > Cand 2
    tie_hierarchy = ["Candidate 0A", "Candidate 0B", "Candidate 1 Unweighted", "Candidate 1 Equal-Crop", "Candidate 2"]
    winning_candidate = None
    for cand in tie_hierarchy:
        if cand in tied_candidates:
            winning_candidate = cand
            break

    print(f"\n  [SELECTION] Winning Candidate Locked: '{winning_candidate}' (CV MAE: {candidate_summary[winning_candidate]['cv_mae']:.6f} t/ha)")
    print(f"  Tied candidates within 1e-7: {tied_candidates}")

    # -------------------------------------------------------------
    # Assemble Unified Prediction Manifests & Reconciliation
    # -------------------------------------------------------------
    pred_dfs = []
    reconciliation_data = {
        "expected_total_rows": total_expected_eval,
        "splits": []
    }

    for sd in splits_data:
        s_id = sd["split_id"]
        ev = sd["eval_df"].copy()
        tr = sd["train_df"]
        n_ev = len(ev)

        # Generate predictions for all candidates
        ev["y_hat_base"] = ev["y_hat_base"]

        # Cand 0A
        ev["pred_cand_0a"] = ev["y_hat_base"] + best_q_0a * tr["residual"].mean()

        # Cand 0B
        r_glob = tr["residual"].mean()
        r_crop = tr.groupby("Crop")["residual"].mean().to_dict()
        ev["pred_cand_0b"] = ev["y_hat_base"] + best_q_0b * ev["Crop"].map(r_crop).fillna(r_glob)

        # Cand 1 Unweighted
        r_c1_unw = sd["c1_unw_models"][best_c1_unw[0]]
        ev["pred_cand_1_unweighted"] = ev["y_hat_base"] + best_c1_unw[1] * r_c1_unw

        # Cand 1 Equal-Crop
        r_c1_eq = sd["c1_eq_models"][best_c1_eq[0]]
        ev["pred_cand_1_equal_crop"] = ev["y_hat_base"] + best_c1_eq[1] * r_c1_eq

        # Candidate 2 Final Predictions & 5-Case Disjoint Routing Reconciliations
        r_c2_unified, pred_cand_2, routing_cases, routing_statuses, routing_counts = route_candidate2_predictions(
            eval_df=ev,
            stratum_models=sd["c2_stratum_models"],
            c2_locked_lambdas=c2_locked_lambdas,
            r_fallback_eval=sd["r_c2_fallback"],
            train_crop_counts=sd["train_crop_counts"],
            tax_crops=tax_crops,
            alpha_multiplier=best_alpha_2
        )
        ev["pred_cand_2"] = pred_cand_2
        ev["cand_2_routing_case"] = routing_cases
        ev["cand_2_routing_status"] = routing_statuses

        active_count = routing_counts["active_count"]
        fallback_ridge_count = routing_counts["fallback_count"]
        zero_corr_total = routing_counts["total_zero_residual"]
        unseen_count = routing_counts["screened_count"] + routing_counts["unseen_count"]
        unmapped_count = routing_counts["unmapped_count"]
        invalid_feat_count = routing_counts["invalid_count"]

        # Winning candidate prediction assignment
        if winning_candidate == "Candidate 0A":
            ev["pred_primary_candidate"] = ev["pred_cand_0a"]
        elif winning_candidate == "Candidate 0B":
            ev["pred_primary_candidate"] = ev["pred_cand_0b"]
        elif winning_candidate == "Candidate 1 Unweighted":
            ev["pred_primary_candidate"] = ev["pred_cand_1_unweighted"]
        elif winning_candidate == "Candidate 1 Equal-Crop":
            ev["pred_primary_candidate"] = ev["pred_cand_1_equal_crop"]
        else:
            ev["pred_primary_candidate"] = ev["pred_cand_2"]

        # Exact Disjoint Reconciliation Assertions
        assert active_count + fallback_ridge_count + zero_corr_total == n_ev, (
            f"Split {s_id} Candidate 2 reconciliation mismatch: {active_count} + {fallback_ridge_count} + {zero_corr_total} != {n_ev}"
        )
        assert len(routing_cases) == n_ev
        assert len(routing_statuses) == n_ev

        reconciliation_data["splits"].append({
            "split_id": s_id,
            "expected_rows": n_ev,
            "c2_active_rows": active_count,
            "c2_fallback_ridge_rows": fallback_ridge_count,
            "c2_zero_correction_rows": zero_corr_total,
            "c2_unseen_rows": unseen_count,
            "c2_unmapped_rows": unmapped_count,
            "c2_invalid_feat_rows": invalid_feat_count,
            "reconciliation_passed": True
        })

        pred_dfs.append(ev)

    all_pred_df = pd.concat(pred_dfs, ignore_index=True)
    assert len(all_pred_df) == total_expected_eval, f"Expected {total_expected_eval} total eval rows, got {len(all_pred_df)}"

    # Denominator parity across all candidate prediction columns
    for col in ["pred_cand_0a", "pred_cand_0b", "pred_cand_1_unweighted", "pred_cand_1_equal_crop", "pred_cand_2", "pred_primary_candidate"]:
        assert len(all_pred_df[col]) == total_expected_eval
        assert np.all(np.isfinite(all_pred_df[col])), f"Non-finite prediction in column {col}"

    print(f"  All reconciliation and denominator parity checks passed ({total_expected_eval} rows).")
    print(f"  Done in {time.time() - t0:.2f}s")

    return all_pred_df, candidate_summary, winning_candidate, stage1_diag, reconciliation_data


